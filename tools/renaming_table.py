"""Generate docs/renaming.md: the Python name of every ported MATLAB function and class.

Usage:
    python tools/renaming_table.py [--out docs/renaming.md]

The table is built from ``monalisa.MATLAB_NAMES`` and from the module docstrings
(``Port of src/<path>.m``). ``python_name`` is the naming rule for new ports; a name that departs
from it needs a reason in ``REASONS`` (tests/unit/test_api.py checks both, and that the
generated file is up to date).
"""

from __future__ import annotations

import argparse
import inspect
import re
import sys
from pathlib import Path

import monalisa

OUT = Path(__file__).parents[1] / "docs" / "renaming.md"

# author initials that prefix upstream names (Bastien Milani, Mauro Leidi, Dominik Helbing, ...)
AUTHOR_PREFIX = re.compile(r"^(bm|mle|dh|ml|bca)(?=[A-Z])")

REASONS = {
    "bmK": "one-letter name; *K* is the deapodization in the Monalisa notation",
    "bmSingle": "`single` would read as the NumPy type",
    "bmImCrope": "spelling",
    "bmEuclideProd": "spelling",
    "bmImage": "`image` is the subpackage `monalisa.image`; the function opens a viewer",
    "bmSparseMat_matlabSparse2bmSparseMat": "shorter, without the inner `bm`",
    "bmTraj_N_u": "`N_u` (grid size) and `n_u` (image size) differ only by case",
    "bmTraj_dK_u": "`dK_u` (grid step) would become `d_k_u`",
    "bmTraj_N_u_dK_u": "returns `N_u` and `dK_u`, see the two lines above",
    "bmVarargin_N_u_dK_u": "default `N_u` and `dK_u` (guessed from the trajectory)",
    "bmVarargin_kernelType_nWin_kernelParam": "default `kernelType`, `nWin` and `kernelParam`",
    "bmVarargin_sparseType": "default `sparseType`",
    "bmTraj_formatTraj": "word repeated",
}

METHODS = {"readMetaData": "read_meta_data", "readRawData": "read_raw_data"}


def python_name(matlab: str, is_class: bool = False) -> str:
    """Naming rule: author prefix removed; classes in CapWords, functions in snake_case,
    a ``2`` between words read as ``to``."""
    name = AUTHOR_PREFIX.sub("", matlab)
    if is_class:
        return name[0].upper() + name[1:]
    name = re.sub(r"(?<=[A-Za-z])2(?=[A-Za-z]{2})", "_to_", name)  # Cell2Array; n2u stays
    name = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)  # camelCase
    name = re.sub(r"(?<=[A-Z])(?=[A-Z][a-z])", "_", name)  # RMSValue
    return re.sub(r"_+", "_", name).lower()


def rows():
    """(subpackage, MATLAB name, upstream file, Python name, note) for every ported name."""
    out = []
    for matlab, target in monalisa.MATLAB_NAMES.items():
        package, name = target.split(".")
        obj = getattr(getattr(monalisa, package), name)
        doc = sys.modules[obj.__module__].__doc__ or ""
        m = re.search(r"\bsrc/\S+?\.m\b", doc)
        if m is None:
            raise ValueError(f"{obj.__module__}: no 'Port of src/....m' in the module docstring")
        rule = python_name(matlab, inspect.isclass(obj))
        note = "" if name == rule else REASONS.get(matlab)
        if note is None:
            raise ValueError(f"{matlab} -> {name}: differs from the rule ({rule}) without a reason in REASONS")
        out.append((package, matlab, m.group(0), name, note))
    return sorted(out, key=lambda r: (r[0], r[3].lower()))


def render() -> str:
    lines = [
        "# Renaming: MATLAB names → Python names",
        "",
        "<!-- generated by tools/renaming_table.py from monalisa.MATLAB_NAMES; do not edit -->",
        "",
        "The upstream MATLAB functions are prefixed with their author's initials (`bm` for Bastien",
        "Milani, `mle` for Mauro Leidi, `dh` for Dominik Helbing). In Python they are named after",
        "what they do, following [PEP 8](https://peps.python.org/pep-0008/#naming-conventions):",
        "",
        "1. the author prefix is removed (`bmMathilda` → `mathilda`, `mleSiemensReader` → `SiemensReader`);",
        "2. functions are in `snake_case` (`bmCoilSense_nonCart_data` → `coil_sense_non_cart_data`),",
        "   classes in `CapWords` (`bmSparseMat` → `SparseMat`), methods too (`readRawData` → `read_raw_data`);",
        "3. a `2` between words means *to* (`bmTraj2SparseMat` → `traj_to_sparse_mat`); in `n2u`",
        "   (non-uniform to uniform) and in dimensions (`bmDFT2`, `_demons23`) it stays;",
        "4. the reconstruction methods keep their Monalisa names (`mathilda`, `sensa`, `teva_morphosia_chain`).",
        "",
        "The names that depart from these rules are explained in the *Note* column. Functions live in",
        "subpackages by topic (`monalisa.recon`, `monalisa.io`, ...) and are all available from the",
        "top-level package: `monalisa.recon.mathilda` is also `monalisa.mathilda`. In code,",
        '`monalisa.find_function("bmMathilda")` returns the Python function of a MATLAB name.',
        "",
        "Not renamed, on purpose:",
        "",
        "- **arguments, struct fields and object properties** keep the MATLAB names (`N_u`, `dK_u`,",
        "  `nCh`, `acquisitionParams.nShot_off`): they are the notation of the Monalisa papers and",
        "  documentation, `N_u` and `n_u` are different quantities, and the fields are compared with",
        "  the MATLAB recordings;",
        "- **option values** that MATLAB scripts pass as strings (`sparseType='bmSparseMat'`,",
        "  `class_type='bmMriAcquisitionParam'`);",
        "- **MATLAB recordings** (`fixtures/matlab/<scenario>/<MATLAB name>/`) and the parity",
        "  tolerances, which refer to the MATLAB functions.",
        "",
        "Python-only public functions (no MATLAB counterpart in `src/`): `monalisa.display.roipoly`",
        "and `poly2mask` (as in MATLAB's Image Processing Toolbox), `monalisa.io.loadmat73` and",
        "`savemat73` (MATLAB v7.3 files).",
        "",
        f"{len(monalisa.MATLAB_NAMES)} functions and classes:",
        "",
    ]
    current = None
    for package, matlab, path, name, note in rows():
        if package != current:
            lines += ["", f"## `monalisa.{package}`", "",
                      "| MATLAB | Upstream file | Python | Note |", "|---|---|---|---|"]
            current = package
        lines.append(f"| `{matlab}` | {path} | `{name}` | {note} |")
    lines += ["", "## Methods", "", "| MATLAB | Python | Classes |", "|---|---|---|"]
    for old, new in METHODS.items():
        lines.append(f"| `{old}` | `{new}` | `RawDataReader`, `SiemensReader`, `IsmrmrdReader` |")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args()
    args.out.write_text(render(), encoding="utf-8")
    print(f"wrote {args.out} ({len(monalisa.MATLAB_NAMES)} names)")


if __name__ == "__main__":
    main()
